var STORAGE_KEY = 'starlinkcat-lang';
var DEFAULT_LANG = 'en';

function getSavedLanguage() {
  try {
    return localStorage.getItem(STORAGE_KEY);
  } catch (e) {
    return null;
  }
}

function saveLanguage(lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch (e) {
    // localStorage unavailable — language choice just won't persist across visits
  }
}

function applyLanguage(lang) {
  var dict = translations[lang] || translations[DEFAULT_LANG];

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-alt]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-alt');
    if (dict[key] !== undefined) {
      el.setAttribute('alt', dict[key]);
    }
  });

  if (dict['meta.title'] !== undefined) {
    document.title = dict['meta.title'];
  }

  document.documentElement.setAttribute('lang', lang);

  var select = document.getElementById('langSelect');
  if (select && select.value !== lang) {
    select.value = lang;
  }

  saveLanguage(lang);
}

document.addEventListener('DOMContentLoaded', function () {
  var initialLang = getSavedLanguage() || DEFAULT_LANG;
  if (!translations[initialLang]) {
    initialLang = DEFAULT_LANG;
  }
  applyLanguage(initialLang);

  var select = document.getElementById('langSelect');
  if (select) {
    select.addEventListener('change', function () {
      applyLanguage(this.value);
    });
  }
});









